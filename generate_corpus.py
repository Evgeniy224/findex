EXTRA_KEYWORDS = [
    "алгоритм", "пам'ять", "сервер", "клієнт", "запит", "результат",
    "оптимізація", "тестування", "метрика", "точність", "повнота",
    "масштабування", "потік", "файл", "каталог", "бібліотека", "модуль"
]


def generate_corpus(output_dir: Path, num_docs: int = 1000, seed: int = 42) -> None:
    rng = random.Random(seed)
    output_dir.mkdir(parents=True, exist_ok=True)

    for i in range(1, num_docs + 1):
        # Обираємо 1 основну тему та 1 додаткову для різноманітності перетинів
        primary_topic = rng.choice(TOPICS)
        secondary_topic = rng.choice(TOPICS)

        # Створюємо підпапки за категоріями (rglob у corpus.py чудово їх прочитає)
        category_dir = output_dir / primary_topic["category"]
        category_dir.mkdir(parents=True, exist_ok=True)

        # Формуємо текст документа від 5 до 18 речень (різна довжина для BM25)
        num_sentences = rng.randint(5, 18)
        chosen_sentences = []

        for _ in range(num_sentences):
            source = primary_topic if rng.random() < 0.75 else secondary_topic
            sentence = rng.choice(source["sentences"])
            chosen_sentences.append(sentence)

        # Додаємо унікальний номер документа, рік та кілька випадкових термінів
        tags = ", ".join(rng.sample(EXTRA_KEYWORDS, k=rng.randint(3, 6)))
        header = f"Документ №{i:04d}. Тема: {primary_topic['title']}."
        footer = f"Ключові теги: {tags}. Ідентифікатор запису: ID-{10000 + i} (редакція 2026 року)."

        full_text = "\n".join([header, "", *chosen_sentences, "", footer])

        file_path = category_dir / f"doc_{i:04d}.txt"
        file_path.write_text(full_text, encoding="utf-8")

    print(f"Успішно згенеровано {num_docs} документів у папці '{output_dir}/'!")


if __name__ == "__main__":
    # За замовчуванням генеруємо 1000 документів (можна змінити на 1200 чи 1500)
    generate_corpus(Path("data"), num_docs=1000)