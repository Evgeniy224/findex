import re
import unicodedata
from typing import Iterator

# Наше задокументоване правило для токенізації:
# Ми шукаємо послідовності літер, цифр та підкреслень (\w+).
# Також ми дозволяємо апострофи (') та дефіси (-),
# але тільки якщо вони знаходяться ВСЕРЕДИНІ слова (наприклад, "п'ять", "будь-який").
# re.UNICODE дозволяє \w розпізнавати кирилицю, літери з наголосами тощо.
TOKEN_PATTERN = re.compile(r"\w+(?:['-]\w+)*", re.UNICODE)


def tokenize(text: str) -> Iterator[str]:
    """
    Перетворює текст на послідовність нормалізованих токенів (слів).

    Правила:
    1. Unicode-нормалізація NFC (щоб 'café' та 'cafe\u0301' вважалися однаковими).
    2. Приведення до нижнього регістру за допомогою casefold().
    3. Пошук слів за допомогою регулярного виразу.
    4. Повернення результату як лінивий генератор (через yield).
    """
    # Крок 1: Нормалізація Unicode
    text = unicodedata.normalize("NFC", text)

    # Крок 2: Casefold (агресивніший за lower(), краще для міжнародних символів)
    text = text.casefold()

    # Крок 3 та 4: Знаходимо всі збіги і віддаємо їх по одному
    for match in TOKEN_PATTERN.finditer(text):
        yield match.group()